import pandas as pd
import numpy as np

# ============================================================
# 1. Загрузка набора данных
# ============================================================
df = pd.read_csv('car_data.csv')

# Убираем служебный столбец-индекс (первый безымянный столбец)
if df.columns[0].startswith('Unnamed') or df.columns[0] == '':
    df = df.drop(columns=df.columns[0])

print("Размер исходного датафрейма:", df.shape)
print(df.head())


# ============================================================
# 2. Анализ пропусков и удаление строк/столбцов с пропусками
# ============================================================
print("\nПропуски по столбцам (до очистки):")
print(df.isna().sum())

# Доля пропусков
print("\nДоля пропусков по столбцам:")
print(df.isna().mean().round(4))

# Удаляем столбцы, где пропусков слишком много (например, > 50%)
threshold = 0.5
cols_to_drop = df.columns[df.isna().mean() > threshold]
df = df.drop(columns=cols_to_drop)
print("\nУдалены столбцы с долей пропусков > 50%:", list(cols_to_drop))

# Удаляем строки, содержащие хотя бы один пропуск
df = df.dropna()
print("Размер датафрейма после удаления пропусков:", df.shape)


# ============================================================
# 3. Средний доход клиентов, купивших Toyota Camry
# ============================================================
camry_income = df.loc[
    (df['Company'] == 'Toyota') & (df['Model'] == 'Camry'),
    'Annual Income'
].mean()

print("\nСредний доход клиентов, купивших Toyota Camry:", camry_income)


# ============================================================
# 4. Топ-10 самых дорогих марок автомобилей за период
# ============================================================
# "Марка" — Company. Считаем среднюю/максимальную цену по марке.
# Ниже — по средней цене (можно заменить на 'max' при необходимости).
top10_brands = (
    df.groupby('Company')['Price ($)']
      .mean()
      .sort_values(ascending=False)
      .head(10)
)
print("\nТоп-10 самых дорогих марок автомобилей (по средней цене):")
print(top10_brands)


# ============================================================
# 5. Средняя стоимость автомобилей по типам кузова (groupby)
# ============================================================
avg_price_by_body = (
    df.groupby('Body Style')['Price ($)']
      .mean()
      .sort_values(ascending=False)
)
print("\nСредняя стоимость автомобилей по типам кузова:")
print(avg_price_by_body)


# ============================================================
# 6. Автомобили 10 клиентов с самым высоким доходом
# ============================================================
top10_rich = (
    df.sort_values('Annual Income', ascending=False)
      .head(10)[['Customer Name', 'Annual Income', 'Company', 'Model', 'Price ($)']]
)
print("\nАвтомобили 10 клиентов с самым высоким доходом:")
print(top10_rich.to_string(index=False))


# ============================================================
# 7. Автомобили 10 клиентов с самым низким доходом
# ============================================================
top10_poor = (
    df.sort_values('Annual Income', ascending=True)
      .head(10)[['Customer Name', 'Annual Income', 'Company', 'Model', 'Price ($)']]
)
print("\nАвтомобили 10 клиентов с самым низким доходом:")
print(top10_poor.to_string(index=False))


# ============================================================
# 8. Новый столбец — логарифм дохода клиента
# ============================================================
# np.log1p безопасен для нулевых значений (log(1+x))
df['Log_Annual_Income'] = np.log1p(df['Annual Income'])

print("\nДатафрейм с новым столбцом Log_Annual_Income:")
print(df[['Annual Income', 'Log_Annual_Income']].head())